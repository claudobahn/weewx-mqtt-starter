def apply_station(c, station):
    """[Station] + [StdArchive]: identity + interval. Driver picked by env (demo overlay)."""
    s = c.setdefault("Station", {})
    s["location"] = str(station.get("location", "Sailing Center"))
    s["latitude"] = str(station.get("latitude", "37.808"))
    s["longitude"] = str(station.get("longitude", "-122.409"))
    alt = station.get("altitude") or {"value": 3, "unit": "foot"}
    # Written as a configobj list `3, foot` (NOT a quoted string -- StdQC and
    # WeeWX's parser handle the list form correctly).
    s["altitude"] = [str(alt.get("value", 3)), str(alt.get("unit", "foot"))]
    # Demo overlay sets WEEWX_DRIVER=simulator; default = real MQTTSubscribe driver.
    s["station_type"] = "Simulator" if USE_SIMULATOR else "MQTTSubscribeDriver"

    arc = c.setdefault("StdArchive", {})
    arc["archive_interval"] = str(station.get("archive_interval", 60))
    arc["record_generation"] = "software"


def apply_mqtt_and_sensors(c, mqtt_cfg, sensors_cfg):
    """[MQTTPublish] (loop -> weather/loop) + [MQTTSubscribeDriver] (rtl_433 ingest).

    Combined so both can share the broker host/port without ordering coupling.
    """
    broker = str(mqtt_cfg.get("broker", "mqtt"))
    port = str(mqtt_cfg.get("port", 1883))

    # [MQTTPublish]: stream every loop packet as JSON to weather/loop. The
    # default unit_system + append_unit_label produce gauge-ready keys
    # (outTemp_F, windSpeed_mph, ...) matching the fuzzy-archer skin.
    c["MQTTPublish"] = {
        "enable": "true",
        "host": broker,
        "port": port,
        "protocol": "MQTTv311",
        "topics": {
            "weather/loop": {
                "publish": "true",
                "type": "json",
                "binding": "loop",
                "unit_system": "US",
                "append_unit_label": "true",
            },
        },
    }

    # [MQTTSubscribeDriver]: translate sensors.sources into the topics map.
    topics = {"unit_system": str(sensors_cfg.get("unit_system", "US"))}
    errors = []
    for sensor in sensors_cfg.get("sources", []) or []:
        name = sensor.get("name", "?")
        topic = sensor.get("topic")
        if not topic:
            errors.append(f"sensor '{name}': missing 'topic'")
            continue
        # Default ON: rtl_433 payloads always carry string metadata (model, mic,
        # protocol, ...) that MQTTSubscribe can't floatify and would otherwise
        # use to reject the whole message. Set `ignore_unmapped: false` to
        # process every field.
        opt_out = bool(sensor.get("ignore_unmapped", True))

        section = {"message": {"type": "json"}}
        if opt_out:
            section["ignore"] = "true"
        if sensor.get("msg_id_field"):
            section["msg_id_field"] = str(sensor["msg_id_field"])

        for field, spec in (sensor.get("fields") or {}).items():
            spec = spec or {}
            entry = {}
            if opt_out:
                entry["ignore"] = "false"          # opt this field back in
            wx_name = spec.get("name", field)
            entry["name"] = wx_name
            if "units" in spec:
                units = spec["units"]
                if units not in weewx.units.conversionDict:
                    errors.append(f"sensor '{name}', field '{field}': unknown units '{units}'")
                elif wx_name not in weewx.units.obs_group_dict:
                    errors.append(f"sensor '{name}', field '{field}': '{wx_name}' "
                                  "is not a known WeeWX observation (can't apply units)")
                else:
                    entry["units"] = units
            if spec.get("contains_total"):
                entry["contains_total"] = "true"
            section[field] = entry
        topics[topic] = section

    if errors:
        sys.exit("station.yaml sensors errors:\n  - " + "\n  - ".join(errors))

    c["MQTTSubscribeDriver"] = {
        "driver": "user.mqttsubscribe",
        "host": broker,
        "port": port,
        "topics": topics,
    }
    c.pop("MQTTSubscribeService", None)

    # Engine services: keep publish (RESTful), drop the subscribe *service*
    # entry the installer added (we use it as the DRIVER, not a service).
    svc = c.setdefault("Engine", {}).setdefault("Services", {})
    remove_from_list(svc, "data_services", "user.mqttsubscribe.MQTTSubscribeService")
    ensure_in_list(svc, "restful_services", "user.mqttpublish.PublishWeeWX")


def apply_credentials(c):
    """Wire MQTT creds from the env (.env) into driver + publish sections."""
    if MQTT_WEEWX_PASS:
        for section in ("MQTTSubscribeDriver", "MQTTPublish"):
            c[section]["username"] = MQTT_WEEWX_USER
            c[section]["password"] = MQTT_WEEWX_PASS


def apply_qc(c, qc):
    """[StdQC][[MinMax]]: per-observation min/max bounds (with optional unit).

    Values are written as configobj lists so they emit unquoted -- a quoted
    `"min, max, unit"` would be mis-parsed by StdQC at runtime.
    """
    if not qc:
        return
    mm = c.setdefault("StdQC", {}).setdefault("MinMax", {})
    for obs, bounds in qc.items():
        out = [str(bounds["min"]), str(bounds["max"])]
        if "unit" in bounds:
            out.append(str(bounds["unit"]))
        mm[obs] = out


def apply_units(c, units):
    """[StdConvert][Group]: force display unit per group.

    `custom_groups` (defining brand-new unit groups) is written into
    `extra_obs.py` instead of weewx.conf -- see apply_observations().
    """
    if not units:
        return
    groups = units.get("groups") or {}
    if groups:
        g = c.setdefault("StdConvert", {}).setdefault("Group", {})
        for grp, unit in groups.items():
            g[grp] = str(unit)


def apply_labels(c, labels):
    """[StdReport][[Defaults]][[[Labels]]][[[[Generic]]]]: per-obs display labels.

    The skin's `$Labels` template variable is built from skin lang.conf merged
    with the REPORT-scoped [StdReport][[Defaults]] / [StdReport][<report>]
    overrides; a top-level [Labels] section in weewx.conf is NOT merged into
    that scope and the skin ignores it. Putting labels under [Defaults] makes
    them apply to every report (matches what fuzzy-archer / mast-buoy expect
    so they land in weewxData.json's `labels.Generic`).

    Idempotent: clears the managed [[[[Generic]]]] block and rebuilds it. Also
    strips any legacy top-level [Labels] block from prior runs.
    """
    c.pop("Labels", None)                         # drop the old (broken) location
    defaults = c.setdefault("StdReport", {}).setdefault("Defaults", {})
    if not labels:
        labs = defaults.get("Labels")
        if labs:
            labs.pop("Generic", None)
            if not labs:
                defaults.pop("Labels", None)
        return
    labs = defaults.setdefault("Labels", {})
    gen = labs.setdefault("Generic", {})
    gen.clear()
    for obs, label in labels.items():
        gen[obs] = str(label)


def _set_extensions_hook(enabled):
    """Idempotently add/remove `import user.extra_obs` (with marker comments) in
    user/extensions.py. That file is imported by the weewx engine BEFORE the
    driver loads, so registrations fire in time for MQTTSubscribe to validate
    custom-obs fields. Without this, even with extra_obs.py written, the driver
    would init before the service loads and reject the custom obs as unknown.
    """
    if not os.path.exists(EXTENSIONS_PY):
        return                                    # baked template missing -- nothing to do
    with open(EXTENSIONS_PY) as f:
        src = f.read()
    # Strip any previous hook so we re-apply cleanly.
    if EXT_HOOK_BEGIN in src and EXT_HOOK_END in src:
        before, _, rest = src.partition(EXT_HOOK_BEGIN)
        _, _, after = rest.partition(EXT_HOOK_END)
        # Drop the trailing newline that was paired with EXT_HOOK_END.
        src = before.rstrip() + ("\n" + after.lstrip("\n") if after.strip() else "\n")
    if enabled:
        block = (
            "\n" + EXT_HOOK_BEGIN + "\n"
            "# Loaded early (before driver init) so observations/custom unit groups\n"
            "# declared in station.yaml are registered when the driver validates fields.\n"
            "import user.extra_obs  # noqa: F401\n"
            + EXT_HOOK_END + "\n"
        )
        src = src.rstrip() + block
    with open(EXTENSIONS_PY, "w") as f:
        f.write(src)


def apply_observations(observations, custom_groups):
    """Write user/extra_obs.py registering obs_group_dict + (optional) custom unit groups.

    Also updates the IN-PROCESS weewx.units dicts so a subsequent apply_*sensors*
    call's validator (which checks `wx_name in weewx.units.obs_group_dict`) sees
    the new observation names -- otherwise the user couldn't add a custom obs
    and reference it from sensors: in the same station.yaml.

    And adds a hook in user/extensions.py to `import user.extra_obs` so the
    registrations fire at engine startup, before the driver loads. Without that
    the driver would init first and reject the custom obs as unknown at RUNTIME
    even though configure.py validation passes.

    Returns True if a service entry should be wired (always True when present).
    """
    if not observations and not custom_groups:
        remove_if_exists(EXTRA_OBS)
        _set_extensions_hook(False)
        return False

    lines = [GENERATED_HEADER,
             "import weewx.units\n",
             "from weewx.engine import StdService\n",
             "\n"]
    # Custom unit groups first (so per-obs registrations below can reference them).
    sys_map = {"US": "USUnits", "Metric": "MetricUnits", "MetricWX": "MetricWXUnits"}
    for grp, units in (custom_groups or {}).items():
        # units may be a dict {US: dBm, Metric: dBm, MetricWX: dBm} or a single str.
        if isinstance(units, str):
            units = {"US": units, "Metric": units, "MetricWX": units}
        for system, unit in units.items():
            attr = sys_map[system]
            lines.append(f"weewx.units.{attr}[{grp!r}] = {unit!r}\n")
            # Register in-process too so the sensors validator accepts this group.
            getattr(weewx.units, attr)[grp] = unit
    for obs in observations or []:
        lines.append(
            f"weewx.units.obs_group_dict[{obs['name']!r}] = {obs['group']!r}\n"
        )
        weewx.units.obs_group_dict[obs["name"]] = obs["group"]
    # Tiny no-op StdService so weewx.conf can list it under prep_services and
    # the module gets loaded (which is what runs the registrations above).
    lines += [
        "\n",
        "class ExtraObservations(StdService):\n",
        "    \"\"\"Loader for the obs_group/unit registrations above.\"\"\"\n",
        "    def __init__(self, engine, config_dict):\n",
        "        super().__init__(engine, config_dict)\n",
    ]
    os.makedirs(USER_DIR, exist_ok=True)
    with open(EXTRA_OBS, "w") as f:
        f.writelines(lines)
    _set_extensions_hook(True)
    return True


def apply_extra_obs_service(c, enable):
    """Wire user.extra_obs.ExtraObservations into prep_services (or remove it)."""
    svc = c.setdefault("Engine", {}).setdefault("Services", {})
    if enable:
        ensure_in_list(svc, "prep_services", "user.extra_obs.ExtraObservations")
    else:
        remove_from_list(svc, "prep_services", "user.extra_obs.ExtraObservations")


def apply_schema(c, schema_cfg):
    """Optional custom DB schema. Generates user/extra_schema.py = base + extras."""
    if not schema_cfg:
        remove_if_exists(EXTRA_SCHEMA)
        # Reset binding to the stock schema if a previous run had pointed it at extra_schema.
        b = c.setdefault("DataBindings", {}).setdefault("wx_binding", {})
        if b.get("schema", "").startswith("user.extra_schema"):
            b["schema"] = "schemas.wview_extended.schema"
        return

    base = str(schema_cfg.get("extends", "wview_extended"))
    extras = list(schema_cfg.get("extra_columns") or [])
    if not extras:
        sys.exit("station.yaml schema: extra_columns must be a non-empty list (omit `schema:` to use the stock schema)")

    lines = [GENERATED_HEADER,
             f"# Extends weewx's built-in `{base}` schema with the columns below.\n",
             "\n",
             "# Support both pip-installed weewx (weewx.schemas) and the weectl-style\n",
             "# layout where schemas live at /data/bin/schemas (alongside /data/bin/user).\n",
             "try:\n",
             f"    from weewx.schemas.{base} import table as _base_table, day_summaries as _base_summaries\n",
             "except ImportError:\n",
             f"    from schemas.{base} import table as _base_table, day_summaries as _base_summaries\n",
             "\n",
             "_extras = [\n"]
    for col in extras:
        lines.append(f"    ({col!r}, 'REAL'),\n")
    lines += [
        "]\n",
        "\n",
        "table = list(_base_table) + _extras\n",
        "day_summaries = list(_base_summaries) + [(c[0], 'scalar') for c in _extras]\n",
        "schema = {'table': table, 'day_summaries': day_summaries}\n",
    ]
    os.makedirs(USER_DIR, exist_ok=True)
    with open(EXTRA_SCHEMA, "w") as f:
        f.writelines(lines)
    # Point the default binding at the generated module.
    c.setdefault("DataBindings", {}).setdefault("wx_binding", {})["schema"] = "user.extra_schema.schema"


