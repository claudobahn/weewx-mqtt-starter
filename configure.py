# ─── small helpers ──────────────────────────────────────────────────────────

def load_yaml(path):
    try:
        with open(path) as h:
            return yaml.safe_load(h) or {}
    except FileNotFoundError:
        sys.exit(f"configure.py: station.yaml not found at {path}")


def ensure_in_list(section, key, value):
    """Make sure `value` is in a configobj list-or-scalar option."""
    cur = section.get(key, [])
    if isinstance(cur, str):
        cur = [cur] if cur else []
    else:
        cur = list(cur)
    if value not in cur:
        cur.append(value)
    section[key] = cur


def remove_from_list(section, key, value):
    """Remove `value` from a configobj list-or-scalar option, if present."""
    cur = section.get(key, [])
    if isinstance(cur, str):
        cur = [cur] if cur else []
    else:
        cur = list(cur)
    section[key] = [v for v in cur if v != value]


def remove_if_exists(path):
    if os.path.exists(path):
        os.remove(path)


