# ─── dashboard (fuzzy-archer skin overrides, written under [StdReport][[Bootstrap]]) ───

def _conv(v):
    """YAML value -> configobj-friendly form (booleans become true/false strings,
    lists pass through as configobj lists, None becomes the literal string 'None')."""
    if v is None:
        return "None"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return [_conv(x) for x in v]
    return str(v)


def _passthrough(section, src, skip=()):
    """Copy a YAML dict into a configobj section, value-translated."""
    if not src:
        return
    for k, v in src.items():
        if k in skip or isinstance(v, dict):    # skip nested dicts (handled by callers)
            continue
        section[k] = _conv(v)


def _replace_section(boot, name):
    """Clear-and-rebuild helper: pop existing subsection, return a fresh one."""
    boot.pop(name, None)
    return boot.setdefault(name, {})


def _items_section(boot, name, key, items):
    """Helper: emit a `[[[<name>]]] <key> = a, b, c` subsection from a list.
    Removes the subsection entirely if items is None (so re-runs are idempotent)."""
    if items is None:
        boot.pop(name, None)
        return
    _replace_section(boot, name)[key] = [str(x) for x in items]


def _emit_stats(boot, stats):
    if not stats:
        boot.pop("Stats", None)
        return
    s = _replace_section(boot, "Stats")
    if "items" in stats:
        s["stats_items"] = [str(x) for x in stats["items"]]
    for obs, agg_list in (stats.get("aggregations") or {}).items():
        obs_s = s.setdefault(obs, {})
        for agg in agg_list:
            obs_s.setdefault(agg, {})


def _emit_history(boot, history):
    if not history:
        boot.pop("HistoryReport", None)
        return
    s = _replace_section(boot, "HistoryReport")
    if "items" in history:
        s["history_items"] = [str(x) for x in history["items"]]


def _emit_news(boot, news):
    """[[[News]]] -- one [[[[<title>]]]] subsection per entry."""
    if not news:
        boot.pop("News", None)
        return
    s = _replace_section(boot, "News")
    for entry in news:
        title = entry.get("title") or entry.get("date") or entry.get("header") or "untitled"
        e = s.setdefault(str(title), {})
        for k in ("header", "body"):
            if k in entry:
                e[k] = str(entry[k])
        # `img:` may be a dict {src, alt, title} or a bare string (src only).
        img = entry.get("img")
        if isinstance(img, dict):
            for k_yaml, k_conf in (("src", "img_src"), ("alt", "img_alt"), ("title", "img_title")):
                if k_yaml in img:
                    e[k_conf] = str(img[k_yaml])
        elif isinstance(img, str):
            e["img_src"] = img


def _emit_live_gauges(boot, gauges_cfg):
    """[[[LiveGauges]]] live_gauge_items + per-obs subsections.

    YAML: { items: [...], gauges: { <obs>: { payload_key, range: {min,max,splitnumber},
            style: {<any fuzzy-archer key>: value} } } }.
    """
    if not gauges_cfg:
        boot.pop("LiveGauges", None)
        return
    s = _replace_section(boot, "LiveGauges")
    gauges = gauges_cfg.get("gauges") or {}
    items = gauges_cfg.get("items") or list(gauges.keys())
    s["live_gauge_items"] = [str(x) for x in items]
    # Top-level options (heatMapEnabled, animation, ...) at the gauges level.
    _passthrough(s, gauges_cfg, skip=("items", "gauges"))
    for obs, spec in gauges.items():
        g = s.setdefault(obs, {})
        if "payload_key" in spec:
            g["payload_key"] = str(spec["payload_key"])
        for yaml_k, conf_k in (("min", "minvalue"), ("max", "maxvalue"), ("splitnumber", "splitnumber")):
            v = (spec.get("range") or {}).get(yaml_k)
            if v is not None:
                g[conf_k] = _conv(v)
        _passthrough(g, spec.get("style") or {})
        _passthrough(g, spec, skip=("payload_key", "range", "style"))


def _emit_live_charts(boot, charts_cfg):
    """[[[LiveCharts]]] live_chart_items + per-chart -> per-series.

    YAML: { items: [...], show_daynight: bool, transition_angle: int,
            charts: { <chart>: { animation: bool, series: [ {obs, payload_key, style: {...}} ] } } }.
    """
    if not charts_cfg:
        boot.pop("LiveCharts", None)
        return
    s = _replace_section(boot, "LiveCharts")
    charts = charts_cfg.get("charts") or {}
    items = charts_cfg.get("items") or list(charts.keys())
    s["live_chart_items"] = [str(x) for x in items]
    _passthrough(s, charts_cfg, skip=("items", "charts"))
    for chart_name, chart_spec in charts.items():
        c = s.setdefault(chart_name, {})
        _passthrough(c, chart_spec, skip=("series",))
        for entry in (chart_spec.get("series") or []):
            name = entry.get("obs") or entry.get("name")
            if not name:
                continue
            sec = c.setdefault(name, {})
            if "payload_key" in entry:
                sec["payload_key"] = str(entry["payload_key"])
            _passthrough(sec, entry.get("style") or {})
            _passthrough(sec, entry, skip=("obs", "name", "payload_key", "style"))


def _emit_image_plots(boot, plots_cfg):
    """[[[ImageGenerator]]] -> [[[[<timespan>_images]]]] -> per-plot subsections.

    YAML: { common: {daynight_*_color, ...},
            day|week|month|year: { style: {line_type, marker_*, aggregate_interval},
                                   items: { <plot>: { yscale, series: [obs | {obs, ...}] } } } }.
    """
    if not plots_cfg:
        boot.pop("ImageGenerator", None)
        return
    s = _replace_section(boot, "ImageGenerator")
    _passthrough(s, plots_cfg.get("common") or {})
    for timespan in ("day", "week", "month", "year"):
        t_cfg = plots_cfg.get(timespan)
        if not t_cfg:
            continue
        ts = s.setdefault(f"{timespan}_images", {})
        items = t_cfg.get("items") or {}
        if items:
            ts["image_items"] = [str(k) for k in items.keys()]
        _passthrough(ts, t_cfg.get("style") or {})
        _passthrough(ts, t_cfg, skip=("items", "style"))
        for plot_name, plot_spec in items.items():
            p = ts.setdefault(plot_name, {})
            if "yscale" in plot_spec:
                p["yscale"] = _conv(plot_spec["yscale"])
            _passthrough(p, plot_spec.get("style") or {})
            _passthrough(p, plot_spec, skip=("yscale", "series", "style"))
            for series in (plot_spec.get("series") or []):
                if isinstance(series, str):
                    p.setdefault(series, {})
                else:
                    name = series.get("obs") or series.get("name")
                    if not name:
                        continue
                    sec = p.setdefault(name, {})
                    _passthrough(sec, series, skip=("obs", "name"))


DASHBOARD_SUBSECTIONS = ("Navigation", "StationInfo", "Stats", "HistoryReport",
                         "News", "LiveGauges", "LiveCharts", "ImageGenerator",
                         "CopyGenerator")


def _emit_copy(boot, copy_cfg):
    """[[[CopyGenerator]]] copy_always / copy_once (lists of file globs)."""
    if not copy_cfg:
        boot.pop("CopyGenerator", None)
        return
    s = _replace_section(boot, "CopyGenerator")
    if "always" in copy_cfg:
        s["copy_always"] = [str(x) for x in copy_cfg["always"]]
    if "once" in copy_cfg:
        s["copy_once"] = [str(x) for x in copy_cfg["once"]]


# ─── branding (user-provided files copied into the skin) ──────────────────

BRANDING_TARGETS = {
    # key in station.yaml.branding -> destination path in the skin
    "logo":                lambda src: os.path.join(SKIN_DIR, "images", os.path.basename(src)),
    "about_page":          lambda _:   os.path.join(SKIN_DIR, "about.html.tmpl"),
    "nav_fragment":        lambda _:   os.path.join(SKIN_DIR, "nav.html.inc"),
    "footer_fragment":     lambda _:   os.path.join(SKIN_DIR, "foot.html.inc"),
    "livegauges_fragment": lambda _:   os.path.join(SKIN_DIR, "livegauges.html.inc"),
}


def _branding_copy(rel_path, dst_path, label):
    # Tolerate the "branding/" prefix users naturally write (paths in YAML look
    # relative to the project root, even though we read from /branding/).
    if rel_path.startswith("branding/"):
        rel_path = rel_path[len("branding/"):]
    src = os.path.join(BRANDING_DIR, rel_path)
    if not os.path.isfile(src):
        sys.exit(f"branding.{label}: file not found at ./branding/{rel_path}")
    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    shutil.copy2(src, dst_path)
    print(f"Branded {label}: {src} -> {dst_path}")


def apply_branding(branding):
    """Copy user-provided files from ./branding/ into the fuzzy-archer skin.

    Re-runs overwrite (idempotent for the files listed in YAML). Removing a key
    does NOT restore the skin's original file (the upstream copy was overwritten
    in /data) -- to revert, remove the file and let a fresh ./data seed re-seed
    the skin from /opt/station. site_name / site_url are informational only;
    the skin doesn't read them, but a user's own HTML fragments can.
    """
    if not branding:
        return
    for key, dst_fn in BRANDING_TARGETS.items():
        src_rel = branding.get(key)
        if src_rel:
            _branding_copy(src_rel, dst_fn(src_rel), key)
    for img_path in (branding.get("images") or []):
        _branding_copy(img_path, os.path.join(SKIN_DIR, "images", os.path.basename(img_path)),
                       f"images/{os.path.basename(img_path)}")


# ─── logging ([Logging] section) ───────────────────────────────────────────

def apply_logging(c, logging_cfg):
    """[Logging]: handlers + formatters + root config.

    Absent  -> restore the default (root: handlers=console, level=INFO; no extras).
    Present -> replace [Logging] entirely with the YAML content (so removing a
               handler from YAML removes it from the conf -- fully idempotent).
    """
    log = c.setdefault("Logging", {})
    log.clear()

    if not logging_cfg:
        # Default: just console at INFO (what the image's baked template carries).
        log["root"] = {"level": "INFO", "handlers": ["console"]}
        return

    for key in ("root", "handlers", "formatters"):
        sub = logging_cfg.get(key)
        if not sub:
            continue
        if key == "root":
            log["root"] = {}
            for k, v in sub.items():
                log["root"][k] = _conv(v)
        else:
            log[key] = {}
            for name, spec in sub.items():
                s = log[key].setdefault(name, {})
                for k, v in (spec or {}).items():
                    s[k] = _conv(v)


# ─── extra services + user-provided modules ────────────────────────────────

def apply_services(c, services_cfg):
    """Add user *_services entries + copy ./user/*.py modules into the skin.

    YAML: { prep: [...], data: [...], restful: [...] }.
    Absent -> no module copy, no entry adds (the publish/extra_obs entries
              that other handlers maintain still apply).
    Present -> for each entry, ensure_in_list into the matching *_services AND
              copy every .py file in ./user/ into /data/bin/user/. One-way copy:
              removing a file from ./user/ does NOT remove it from /data/bin/user/
              (rm by hand or rebuild ./data to clean up).
    """
    if not services_cfg:
        return

    # Copy user modules so the entries below can resolve.
    if os.path.isdir(USER_DIR_SRC):
        os.makedirs(USER_DIR, exist_ok=True)
        for fname in os.listdir(USER_DIR_SRC):
            src = os.path.join(USER_DIR_SRC, fname)
            if os.path.isfile(src) and fname.endswith(".py"):
                dst = os.path.join(USER_DIR, fname)
                shutil.copy2(src, dst)
                print(f"User module: {src} -> {dst}")

    svc = c.setdefault("Engine", {}).setdefault("Services", {})
    for yaml_key, conf_key in (("prep",    "prep_services"),
                               ("data",    "data_services"),
                               ("restful", "restful_services")):
        for entry in (services_cfg.get(yaml_key) or []):
            ensure_in_list(svc, conf_key, str(entry))


def apply_dashboard(c, dashboard):
    """Emit [StdReport][[Bootstrap]] subsections from station.yaml's `dashboard:` block.

    Idempotent: each helper removes its subsection when its YAML key is absent,
    so reruns always reflect the current YAML (no stale overrides). When the
    entire `dashboard:` is absent, all dashboard-managed subsections are removed
    and fuzzy-archer's skin.conf defaults apply.
    """
    boot = c.setdefault("StdReport", {}).setdefault("Bootstrap", {})
    if not dashboard:
        for name in DASHBOARD_SUBSECTIONS:
            boot.pop(name, None)
        return
    _items_section(boot, "Navigation",  "navigation_items",   dashboard.get("navigation"))
    _items_section(boot, "StationInfo", "station_info_items", dashboard.get("station_info"))
    _emit_stats(boot,        dashboard.get("stats"))
    _emit_history(boot,      dashboard.get("history"))
    _emit_news(boot,         dashboard.get("news"))
    _emit_live_gauges(boot,  dashboard.get("live_gauges"))
    _emit_live_charts(boot,  dashboard.get("live_charts"))
    _emit_image_plots(boot,  dashboard.get("image_plots"))
    _emit_copy(boot,         dashboard.get("copy"))


def apply_skin(yml):
    """skin.conf: live-gauge WebSocket URL + dashboard creds for the browser."""
    ws_url = WS_URL_ENV or str((yml.get("mqtt") or {}).get("websocket_url") or "ws://localhost:9001")
    s = configobj.ConfigObj(SKIN, file_error=True)
    jg = s.setdefault("JSONGenerator", {})
    jg["enabled"] = "true"
    conns = jg.setdefault("MQTT", {}).setdefault("connections", {})
    conns.clear()
    conns["local_broker"] = {
        "broker_connection": ws_url,
        "topics": {"weather/loop": {"type": "JSON"}},
    }
    # Read-only dashboard account. NOTE: these creds are embedded in the public
    # weewxData.json, so the account must stay read-only and scoped (see acl).
    if MQTT_DASH_PASS:
        conns["local_broker"]["mqtt_username"] = MQTT_DASH_USER
        conns["local_broker"]["mqtt_password"] = MQTT_DASH_PASS
    s.write()
    print("Patched", SKIN, "-> broker", ws_url)


def patch_jsonengine():
    """Two in-place patches to the installed fuzzy-archer jsonengine.py:

      1. convert() called with a bare string instead of a ValueTuple raises
         "string index out of range" whenever Station altitude is in 'foot'.
      2. On an empty archive database (fresh start, before the first archive
         record) lastGoodStamp is None and `lastGoodStamp - 1` raises
         TypeError. The Cheetah generator skips this case gracefully
         ("cannot find start time"); make JSONGenerator do the same.

    Warns loudly if a target moves upstream (so a maintainer notices).
    """
    path = "/data/bin/user/jsonengine.py"
    patches = [
        (
            "altitude convert bug",
            "altitude_m = convert(altitude[0], 'meter')[0]",
            "altitude_m = convert((float(altitude[0]), 'foot', 'group_altitude'), 'meter')[0]",
        ),
        (
            "empty-database guard",
            "            if enabled:\n                self.setup()\n                self.gen_data()",
            "            if enabled:\n"
            "                if self.db_binder.get_manager().lastGoodStamp() is None:\n"
            "                    log.info('JSONGenerator: empty archive database, skipping until data arrives')\n"
            "                    return\n"
            "                self.setup()\n"
            "                self.gen_data()",
        ),
    ]
    with open(path) as f:
        src = f.read()
    for label, old, new in patches:
        if new in src:
            continue
        if old in src:
            src = src.replace(old, new)
            print("Patched", path, f"({label})")
        else:
            print(f"WARNING: {path} ({label}): patch target not found; "
                  "fuzzy-archer may have changed upstream -- review configure.py.",
                  file=sys.stderr)
    with open(path, "w") as f:
        f.write(src)


