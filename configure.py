#!/usr/bin/env python3
"""Compile station.yaml into weewx.conf + skin.conf + generated user/*.py modules.

Run inside the weewx container; configobj/yaml/weewx are baked in:

    docker compose run --rm --entrypoint python weewx /configure.py

Reads:
  /station.yaml  (the one source of configurable truth; secrets stay in .env)

Writes:
  /data/weewx.conf
  /data/skins/Bootstrap/skin.conf
  /data/bin/user/extra_obs.py     (only if `observations:` / `units.custom_groups:` set)
  /data/bin/user/extra_schema.py  (only if `schema:` set)

Env overrides (overlay-controlled, not user-edited config):
  WEEWX_DRIVER     (mqtt | simulator)        — set by docker-compose.demo.yml
  WEEWX_WS_URL     (ws/wss URL)              — set by prod overlay to wss://$DOMAIN
  MQTT_WEEWX_USER  MQTT_WEEWX_PASS           — broker creds for driver + publish
  MQTT_DASH_USER   MQTT_DASH_PASS            — read-only creds embedded in skin

The file is organised as one `apply_<section>(...)` per top-level YAML key,
called from `main()`. Phase 2/3 will plug in `apply_dashboard`, `apply_branding`,
`apply_logging`, `apply_services` -- the data flow is the same shape.
"""
